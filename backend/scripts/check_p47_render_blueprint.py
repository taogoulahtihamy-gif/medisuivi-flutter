#!/usr/bin/env python3
"""Fail-closed validation of P4.7/P5.0 Render staging Blueprints.

Requires PyYAML in disposable CI, never touches credentials or deployments.
"""
from pathlib import Path
import yaml


BRANCH = "feat/medisuivi-p50-remote-web-android-sandbox"


def checked_env(service):
    items = service["envVars"]
    assert isinstance(items, list)
    assert all(isinstance(item, dict) and "key" in item for item in items)
    env = {item["key"]: item for item in items}
    assert len(env) == len(items), "Duplicate env keys"
    return env


def assert_api(service):
    for key, expected in {
        "type": "web",
        "name": "medisuivi-api-staging",
        "runtime": "python",
        "plan": "free",
        "rootDir": "backend",
        "healthCheckPath": "/ready",
    }.items():
        assert service.get(key) == expected, key
    assert service.get("autoDeployTrigger") in ("off", False), "No auto deploy"
    assert service.get("buildCommand") == "pip install -r requirements.txt"
    cmd = service.get("startCommand", "")
    assert cmd.startswith("python -m alembic upgrade head && ")
    assert "uvicorn app.main:app" in cmd and "--port $PORT" in cmd
    env = checked_env(service)
    assert env["APP_DATABASE_URL"] == {
        "key": "APP_DATABASE_URL", "sync": False,
    }, "DB URL must be a private Render environment variable"
    assert env["APP_JWT_SECRET"] == {
        "key": "APP_JWT_SECRET", "generateValue": True,
    }, "JWT must be uniquely generated by Render"
    for key in ("APP_ALLOW_DEVELOPMENT_REGISTRATION", "APP_ENABLE_EMAIL_AUTH"):
        assert str(env[key].get("value")).lower() == "false", key
    return env


def check():
    root = Path(__file__).resolve().parents[2]
    data = yaml.safe_load((root / "render.yaml").read_text())
    assert isinstance(data, dict)
    assert "databases" not in data, "Use new EMPTY Neon PostgreSQL only"
    services = data.get("services")
    assert isinstance(services, list) and services, "Missing Render services"
    names = {item["name"] for item in services}
    assert len(names) == len(services)

    if names == {"medisuivi-api-staging"}:
        # Historical P4.7 read-only blueprint, still safe.
        assert len(services) == 1
        service = services[0]
        assert service["branch"] == "feat/medisuivi-p47-render-neon-staging"
        env = assert_api(service)
        assert env["APP_ENV"]["value"] == "staging"
        assert set(env) == {
            "APP_ENV", "APP_ALLOW_DEVELOPMENT_REGISTRATION",
            "APP_ENABLE_EMAIL_AUTH", "APP_DATABASE_URL", "APP_JWT_SECRET",
        }
        print("P4.7 read-only Render blueprint safe")
        return

    assert names == {"medisuivi-api-staging", "medisuivi-web-staging"}
    assert all(item.get("branch") == BRANCH for item in services)
    api = next(item for item in services if item["name"] == "medisuivi-api-staging")
    web = next(item for item in services if item["name"] == "medisuivi-web-staging")
    env = assert_api(api)
    assert env["APP_ENV"]["value"] == "sandbox"
    assert str(env["APP_SANDBOX_WRITES_ENABLED"]["value"]).lower() == "true"
    assert str(env["APP_SANDBOX_REGISTRATION_ENABLED"]["value"]).lower() == "true"
    assert env["APP_SANDBOX_INVITE_CODE"] == {
        "key": "APP_SANDBOX_INVITE_CODE", "sync": False,
    }, "Invitation MUST NOT be committed or compiled into Flutter"
    assert env["APP_PUBLIC_WEB_ORIGIN"]["value"] == (
        "https://medisuivi-web-staging.onrender.com")
    assert set(env) == {
        "APP_ENV", "APP_PUBLIC_WEB_ORIGIN",
        "APP_SANDBOX_WRITES_ENABLED", "APP_SANDBOX_REGISTRATION_ENABLED",
        "APP_SANDBOX_INVITE_CODE", "APP_ALLOW_DEVELOPMENT_REGISTRATION",
        "APP_ENABLE_EMAIL_AUTH", "APP_DATABASE_URL", "APP_JWT_SECRET",
    }, "Unexpected environment variable added to public sandbox"

    assert web["type"] == "web" and web["runtime"] == "static"
    assert web.get("autoDeployTrigger") in ("off", False)
    assert web["buildCommand"] == "bash scripts/build_render_web.sh"
    assert web["staticPublishPath"] == "build/web"
    env_web = checked_env(web)
    assert env_web == {
        "MEDISUIVI_API_BASE_URL": {
            "key": "MEDISUIVI_API_BASE_URL",
            "value": "https://medisuivi-api-staging.onrender.com",
        },
    }, "No secrets in public Flutter bundle"
    assert any(route.get("source") == "/*" and route.get("destination") == "/index.html"
               for route in web.get("routes", []))
    print("P5.0 remote HTTPS sandbox: API, Web and Neon credential boundaries safe")


if __name__ == "__main__":
    check()
