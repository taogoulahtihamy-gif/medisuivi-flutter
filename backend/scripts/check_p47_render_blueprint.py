#!/usr/bin/env python3
"""P4.7 safety gate for the Render staging blueprint.

Requires PyYAML, installed only in the isolated CI job.
"""
from pathlib import Path

import yaml


def check():
    root = Path(__file__).resolve().parents[2]
    data = yaml.safe_load((root / "render.yaml").read_text())
    assert isinstance(data, dict)
    assert "databases" not in data, "External disposable Neon database expected"
    services = data.get("services")
    assert isinstance(services, list) and len(services) == 1
    service = services[0]
    for key, expected in {
        "type": "web",
        "name": "medisuivi-api-staging",
        "runtime": "python",
        "plan": "free",
        "rootDir": "backend",
        "branch": "feat/medisuivi-p47-render-neon-staging",
        "autoDeployTrigger": "off",
        "healthCheckPath": "/ready",
    }.items():
        assert service.get(key) == expected, key

    assert service.get("buildCommand") == "pip install -r requirements.txt"
    command = service.get("startCommand", "")
    assert command.startswith("python -m alembic upgrade head && ")
    assert "uvicorn app.main:app" in command and "--port $PORT" in command
    vars_ = service["envVars"]
    assert all(isinstance(item, dict) for item in vars_)
    env = {item["key"]: item for item in vars_}
    assert len(vars_) == len(env), "Duplicate variables forbidden"

    for key, expected in {
        "APP_ENV": "staging",
        "APP_ALLOW_DEVELOPMENT_REGISTRATION": "false",
        "APP_ENABLE_EMAIL_AUTH": "false",
    }.items():
        assert str(env[key].get("value")).lower() == expected, key
    assert env["APP_DATABASE_URL"] == {
        "key": "APP_DATABASE_URL", "sync": False,
    }, "Never commit a PostgreSQL password to Git"
    assert env["APP_JWT_SECRET"] == {
        "key": "APP_JWT_SECRET", "generateValue": True,
    }, "JWT must be generated by Render"
    assert not (set(env) - {
        "APP_ENV", "APP_ALLOW_DEVELOPMENT_REGISTRATION",
        "APP_ENABLE_EMAIL_AUTH", "APP_DATABASE_URL", "APP_JWT_SECRET",
    }), "Unexpected security-sensitive environment value"
    print("P4.7 Render blueprint safety: staging only, no credentials in Git")


if __name__ == "__main__":
    check()
